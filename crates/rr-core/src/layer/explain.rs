//! Per-field provenance: which layer of a stack set a field, and what it
//! overrode.
//!
//! # Model
//!
//! Provenance is computed **on demand**, by walking the stack again for
//! the one field asked about ([`Layered::explain`]), never recorded during
//! a merge. A merge stays the plain fold of the [*Laws*](super#laws) and
//! costs nothing extra when no one asks; `explain` is for debugging a
//! definition ("why is this table signed?"), asked about one field at a
//! time. It is exact for every policy, because each layer's own document
//! is in the stack ([`Lineage::stack`](super::Lineage::stack) holds every
//! layer a resolved document came from, each the registered `Arc`), and the
//! effect a layer has on one field depends only on that layer's own
//! document along the field's path:
//!
//! * nothing, if a container on the path is not mentioned (a nested
//!   document unset, a keyed item absent) and the field itself is not;
//! * the layer's own state of the field, applied on top of the inherited
//!   one ([`Change::Apply`]);
//! * a **reset**, if the layer replaces a container on the path
//!   ([`Nested::Replace`]): the inherited field is dropped and the layer's
//!   own state, if any, is all that is left ([`Change::Reset`]);
//! * a **removal**, if the layer omits a container on the path
//!   ([`Nested::Omit`], [`Change::Removed`]).
//!
//! Folding those changes over the stack, weakest first, gives the merged
//! field: a `Patch` over an omitted container is a `Replace`
//! ([`Nested`]), which starts from nothing, as an apply over a removal
//! does. The values an [`Explanation`] reports are borrowed from the
//! layers' documents, never copied.
//!
//! # Paths
//!
//! A [`FieldPath`] names a field from the top of a document, built from
//! typed accessors, so a path to a field that does not exist, or that goes
//! through a keyed list with a key of the wrong type, does not compile:
//!
//! ```text
//! FieldPath::root().field("tables", |r: &Rom| &r.tables).item(name)
//!     .field("scaling", |t| &t.scaling).nested().field("units", |s| &s.units)
//! ```
//!
//! reads `tables["Boost Target"].scaling.units` (for that `name`; full
//! example below). A closure per field rather
//! than accessors generated by [`merge_fields!`](crate::merge_fields): the
//! macro would have to generate a path type per struct, and the closures
//! already say everything the walk needs (which field, which policy, from
//! its type). Field names are given as text only to display the path.
//!
//! # Explanations
//!
//! An [`Explanation`] is the list of layers that changed the field, each a
//! [`Step`] with its layer (and so its [`Provenance`]) and its [`Change`].
//! Every listing of steps is **strongest first**: the winning layer, then
//! each value it overrode, down to the weakest. What the field resolved to
//! and what each step means depends on the field's policy, so each policy
//! has its own view:
//!
//! | Field type | Resolved value | Steps |
//! |------------|----------------|-------|
//! | [`Field<T>`] | [`value`](Explanation::value): the winning set value | the winner, then every value it overrides |
//! | [`Nested<P>`] | [`is_present`](Explanation::is_present) | [`actions`](Explanation::actions): added, modified, replaced, omitted, restored |
//! | [`Keyed<K, P>`] | [`keys`](Explanation::keys), in list order | one [`item`](Explanation::item) explanation per key |
//! | [`Appended<T>`] | [`items`](Explanation::items) | [`live`](Explanation::live) contributions and the ones a replace [`dropped`](Explanation::dropped) |
//!
//! Each view's [`Display`](fmt::Display) is a multi-line report, as in
//! this MF-06 case (signedness overridden by the child):
//!
//! ```
//! use rr_core::diag::Span;
//! use rr_core::encoding::Storage;
//! use rr_core::layer::{Field, FieldPath, Keyed, Layer, LayerKind, Layered, Nested};
//!
//! #[derive(Debug, Clone, Default, PartialEq)]
//! struct Scaling {
//!     units: Field<String>,
//! }
//! rr_core::merge_fields!(Scaling { units });
//!
//! #[derive(Debug, Clone, Default, PartialEq)]
//! struct Table {
//!     storage: Field<Storage>,
//!     scaling: Nested<Scaling>,
//! }
//! rr_core::merge_fields!(Table { storage, scaling });
//!
//! #[derive(Debug, Clone, Default, PartialEq)]
//! struct Rom {
//!     tables: Keyed<String, Table>,
//! }
//! rr_core::merge_fields!(Rom { tables });
//!
//! let rom = |storage| {
//!     let mut rom = Rom::default();
//!     let table = Table { storage: Field::Set(storage), ..Table::default() };
//!     rom.tables.patch("Boost Target".to_owned(), table);
//!     rom
//! };
//! let file = |id: &str, line| {
//!     Layer::new(id.into(), LayerKind::File, format!("{id}.xml"), Span::line_col(line, 1))
//! };
//! let mut stack = Layered::new();
//! stack.push(file("16BITBASE", 3), rom(Storage::U16));
//! stack.push(file("A2WC522N", 2), rom(Storage::I16));
//!
//! let table = FieldPath::root()
//!     .field("tables", |r: &Rom| &r.tables)
//!     .item("Boost Target".to_owned());
//! let storage = table.clone().field("storage", |t: &Table| &t.storage);
//! let explained = stack.explain(&storage);
//! assert_eq!(explained.value(), Some(&Storage::I16));
//! assert_eq!(
//!     explained.to_string(),
//!     "tables[\"Boost Target\"].storage = I16
//!   set to I16 at A2WC522N.xml:2:1 [layer A2WC522N]
//!   overrides:
//!     set to U16 at 16BITBASE.xml:3:1 [layer 16BITBASE]"
//! );
//!
//! // `tables["Boost Target"].scaling.units`: no layer sets it.
//! let units = table
//!     .field("scaling", |t: &Table| &t.scaling)
//!     .nested()
//!     .field("units", |s: &Scaling| &s.units);
//! assert!(stack.explain(&units).winner().is_none());
//! ```
//!
//! A layer's provenance is where its document starts
//! ([`Layer::provenance`]): partial documents carry no span per field.

