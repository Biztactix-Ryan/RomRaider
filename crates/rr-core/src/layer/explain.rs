/// A field state an [`Explanation`] can be computed for: one of the merge
/// policies of this module.
pub trait Explain: Merge {
    /// `true` if applying this state on top of any other changes nothing:
    /// an unset [`Field`] or [`Nested`], an empty [`Keyed`] list, an
    /// [`Appended`] that appends nothing. A layer whose state is a no-op is
    /// not a step of an explanation.
    fn is_noop(&self) -> bool;
}

impl<T: Clone> Explain for Field<T> {
    fn is_noop(&self) -> bool {
        self.is_unset()
    }
}

impl<P: Merge + Clone> Explain for Nested<P> {
    fn is_noop(&self) -> bool {
        self.is_unset()
    }
}

impl<K: Ord + Clone, P: Merge + Clone> Explain for Keyed<K, P> {
    fn is_noop(&self) -> bool {
        self.is_empty()
    }
}

impl<T: Clone> Explain for Appended<T> {
    fn is_noop(&self) -> bool {
        !self.replaces() && self.items().is_empty()
    }
}

/// What one layer's document says at a path: see [`FieldPath`].
enum Reach<'a, L> {
    /// The walk reached the field (`leaf`) or stopped at a container the
    /// layer does not mention (`None`). `reset` is the outermost container
    /// on the way that the layer replaces.
    At {
        reset: Option<Arc<str>>,
        leaf: Option<&'a L>,
    },
    /// The layer omits this container on the way.
    Omitted(Arc<str>),
}

/// The walk of one path through one document.
type Walk<P, L> = dyn for<'a> Fn(&'a P) -> Reach<'a, L> + Send + Sync;

/// `f` as a [`Walk`]: the bound gives a closure its higher-ranked
/// signature.
fn walk<P, L, F>(f: F) -> Arc<Walk<P, L>>
where
    F: for<'a> Fn(&'a P) -> Reach<'a, L> + Send + Sync + 'static,
{
    Arc::new(f)
}

/// A typed path from the top of a document `P` to a field of type `L`
/// (module docs, *Paths*).
///
/// Built from [`FieldPath::root`] with [`field`](Self::field) (a field of a
/// struct), [`nested`](Self::nested) (into a [`Nested`] document),
/// [`key`](Self::key) (an entry of a [`Keyed`] list) and
/// [`item`](Self::item) (`key` then `nested`). Cheap to clone.
pub struct FieldPath<P, L> {
    text: Arc<str>,
    walk: Arc<Walk<P, L>>,
}

impl<P, L> Clone for FieldPath<P, L> {
    fn clone(&self) -> Self {
        Self {
            text: Arc::clone(&self.text),
            walk: Arc::clone(&self.walk),
        }
    }
}

/// The path text.
impl<P, L> fmt::Debug for FieldPath<P, L> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_tuple("FieldPath").field(&self.text).finish()
    }
}

/// The path text, such as `tables["Boost Target"].scaling.units`; the
/// root is `(document)`.
impl<P, L> fmt::Display for FieldPath<P, L> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(display_path(&self.text))
    }
}

/// `text`, or `(document)` for the root.
fn display_path(text: &str) -> &str {
    if text.is_empty() { "(document)" } else { text }
}

impl<P: 'static> FieldPath<P, P> {
    /// The whole document.
    #[must_use]
    pub fn root() -> Self {
        Self {
            text: "".into(),
            walk: walk(|doc| Reach::At {
                reset: None,
                leaf: Some(doc),
            }),
        }
    }
}

impl<P: 'static, L: 'static> FieldPath<P, L> {
    /// The path as text: `tables["Boost Target"].scaling.units`, empty for
    /// the root.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.text
    }

    /// The field `name` of the struct this path names, read by `get`.
    #[must_use]
    pub fn field<M: 'static>(
        self,
        name: &str,
        get: impl for<'a> Fn(&'a L) -> &'a M + Send + Sync + 'static,
    ) -> FieldPath<P, M> {
        let text = if self.text.is_empty() {
            name.into()
        } else {
            format!("{}.{name}", self.text).into()
        };
        let inner = self.walk;
        FieldPath {
            text,
            walk: walk(move |doc| match inner(doc) {
                Reach::At { reset, leaf } => Reach::At {
                    reset,
                    leaf: leaf.map(&get),
                },
                Reach::Omitted(by) => Reach::Omitted(by),
            }),
        }
    }

    /// The field in `doc`, if every container on the way is present: the
    /// resolved field when `doc` is a merged document.
    #[must_use]
    pub fn get<'a>(&self, doc: &'a P) -> Option<&'a L> {
        match (self.walk)(doc) {
            Reach::At { leaf, .. } => leaf,
            Reach::Omitted(_) => None,
        }
    }
}

impl<P: 'static, Q: 'static> FieldPath<P, Nested<Q>> {
    /// The document inside the [`Nested`] state this path names. The text
    /// is unchanged: `tables["A"].scaling` names both the state and the
    /// document in it.
    #[must_use]
    pub fn nested(self) -> FieldPath<P, Q> {
        let text = self.text;
        let inner = self.walk;
        FieldPath {
            text: Arc::clone(&text),
            walk: walk(move |doc| match inner(doc) {
                Reach::At {
                    reset,
                    leaf: Some(state),
                } => match state {
                    Nested::Unset => Reach::At { reset, leaf: None },
                    Nested::Patch(q) => Reach::At {
                        reset,
                        leaf: Some(q),
                    },
                    Nested::Replace(q) => Reach::At {
                        reset: reset.or_else(|| Some(Arc::clone(&text))),
                        leaf: Some(q),
                    },
                    Nested::Omit => Reach::Omitted(Arc::clone(&text)),
                },
                Reach::At { reset, leaf: None } => Reach::At { reset, leaf: None },
                Reach::Omitted(by) => Reach::Omitted(by),
            }),
        }
    }
}

impl<P: 'static, K, Q: 'static> FieldPath<P, Keyed<K, Q>>
where
    K: PartialEq + fmt::Debug + Send + Sync + 'static,
{
    /// The entry for `key` of the [`Keyed`] list this path names: an absent
    /// entry is not mentioned. Displayed as `tables["Boost Target"]` (the
    /// key's `Debug`).
    #[must_use]
    pub fn key(self, key: K) -> FieldPath<P, Nested<Q>> {
        let text = format!("{}[{key:?}]", self.text).into();
        let inner = self.walk;
        FieldPath {
            text,
            walk: walk(move |doc| match inner(doc) {
                Reach::At { reset, leaf } => Reach::At {
                    reset,
                    leaf: leaf.and_then(|list| list.get(&key)),
                },
                Reach::Omitted(by) => Reach::Omitted(by),
            }),
        }
    }

    /// The item for `key`: [`key`](Self::key) then
    /// [`nested`](FieldPath::nested).
    #[must_use]
    pub fn item(self, key: K) -> FieldPath<P, Q> {
        self.key(key).nested()
    }
}

/// What one layer did to a field ([`Step`]).
#[derive(Debug, Clone, PartialEq)]
pub enum Change<'a, L> {
    /// The layer's own state of the field, applied on top of the inherited
    /// one. Never a no-op ([`Explain::is_noop`]).
    Apply(&'a L),
    /// The layer replaced the container `by` (a path), dropping the
    /// inherited field; `leaf` is the layer's own state of the field, if it
    /// has one, which is all that is left.
    Reset {
        /// The replaced container's path.
        by: Arc<str>,
        /// The layer's own state of the field.
        leaf: Option<&'a L>,
    },
    /// The layer omitted the container `by` (a path), and the field with
    /// it.
    Removed {
        /// The omitted container's path.
        by: Arc<str>,
    },
}

impl<'a, L> Change<'a, L> {
    /// The layer's own state of the field, if it has one.
    #[must_use]
    pub fn leaf(&self) -> Option<&'a L> {
        match self {
            Self::Apply(leaf) => Some(*leaf),
            Self::Reset { leaf, .. } => *leaf,
            Self::Removed { .. } => None,
        }
    }
}

/// Why a change happened, if not by the layer's own state: ` (X replaced)`
/// or ` (X omitted)`, empty for an apply.
struct Cause<'c, 'a, L>(&'c Change<'a, L>);

impl<L> fmt::Display for Cause<'_, '_, L> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.0 {
            Change::Apply(_) => Ok(()),
            Change::Reset { by, .. } => write!(f, " ({by} replaced)"),
            Change::Removed { by } => write!(f, " ({by} omitted)"),
        }
    }
}

/// One layer that changed a field: the layer and what it did.
#[derive(Debug, Clone, PartialEq)]
pub struct Step<'a, L> {
    layer: &'a Layer,
    change: Change<'a, L>,
}

impl<'a, L> Step<'a, L> {
    /// The layer.
    #[must_use]
    pub fn layer(&self) -> &'a Layer {
        self.layer
    }

    /// What it did.
    #[must_use]
    pub fn change(&self) -> &Change<'a, L> {
        &self.change
    }

    /// Where the layer's document is: [`Layer::provenance`].
    #[must_use]
    pub fn provenance(&self) -> Provenance {
        self.layer.provenance()
    }
}

/// Writes one report line: `what` at the step's provenance, indented.
fn line<L>(
    f: &mut fmt::Formatter<'_>,
    indent: usize,
    step: &Step<'_, L>,
    what: impl fmt::Display,
) -> fmt::Result {
    write!(
        f,
        "\n{:indent$}{what}{} at {}",
        "",
        Cause(&step.change),
        step.provenance()
    )
}

/// The layers of a stack that changed one field (module docs,
/// *Explanations*). Computed by [`Layered::explain`].
#[derive(Debug, Clone, PartialEq)]
pub struct Explanation<'a, L> {
    path: Arc<str>,
    steps: Vec<Step<'a, L>>,
}

impl<P> Layered<P> {
    /// Which layers set the field at `path`, and what each one overrode
    /// (module docs, *Explanations*).
    #[must_use]
    pub fn explain<L: Explain>(&self, path: &FieldPath<P, L>) -> Explanation<'_, L> {
        let steps = self
            .layers
            .iter()
            .filter_map(|(layer, doc)| {
                let change = match (path.walk)(doc) {
                    Reach::At { reset: None, leaf } => {
                        Change::Apply(leaf.filter(|l| !l.is_noop())?)
                    }
                    Reach::At {
                        reset: Some(by),
                        leaf,
                    } => Change::Reset { by, leaf },
                    Reach::Omitted(by) => Change::Removed { by },
                };
                Some(Step { layer, change })
            })
            .collect();
        Explanation {
            path: Arc::clone(&path.text),
            steps,
        }
    }
}

impl<'a, L> Explanation<'a, L> {
    /// The path explained, as text ([`FieldPath::as_str`]).
    #[must_use]
    pub fn path(&self) -> &str {
        &self.path
    }

    /// Every layer that changed the field, strongest first.
    pub fn history(&self) -> impl ExactSizeIterator<Item = &Step<'a, L>> {
        self.steps.iter().rev()
    }

    /// The strongest layer that changed the field: the one whose change
    /// stands. `None` if no layer mentions it.
    #[must_use]
    pub fn winner(&self) -> Option<&Step<'a, L>> {
        self.steps.last()
    }

    /// Every layer below the [`winner`](Self::winner) that changed the
    /// field, strongest first.
    pub fn overridden(&self) -> impl Iterator<Item = &Step<'a, L>> {
        self.history().skip(1)
    }
}

// ---- Field ----

impl<'a, T> Explanation<'a, Field<T>> {
    /// The resolved value: the [`winner`](Self::winner)'s, if it sets one.
    /// `None` if the field is unset, omitted, or in an omitted container.
    #[must_use]
    pub fn value(&self) -> Option<&'a T> {
        self.winner()?.change.leaf()?.get()
    }
}

/// One step of a [`Field`]: `set to V`, `omitted`, `cleared` (a replaced
/// container that does not set it) or `removed`.
fn field_line<T: fmt::Debug>(
    f: &mut fmt::Formatter<'_>,
    indent: usize,
    step: &Step<'_, Field<T>>,
) -> fmt::Result {
    match (&step.change, step.change.leaf()) {
        (Change::Removed { .. }, _) => line(f, indent, step, "removed"),
        (_, Some(Field::Set(v))) => line(f, indent, step, format_args!("set to {v:?}")),
        (_, Some(Field::Omit)) => line(f, indent, step, "omitted"),
        (_, Some(Field::Unset) | None) => line(f, indent, step, "cleared"),
    }
}

/// `path = V` or `path: no value`, then the winner and what it overrides.
impl<T: fmt::Debug> fmt::Display for Explanation<'_, Field<T>> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let path = display_path(&self.path);
        match self.value() {
            Some(v) => write!(f, "{path} = {v:?}")?,
            None => write!(f, "{path}: no value")?,
        }
        let Some(winner) = self.winner() else {
            return f.write_str("\n  not set by any layer");
        };
        field_line(f, 2, winner)?;
        let mut overridden = self.overridden().peekable();
        if overridden.peek().is_some() {
            f.write_str("\n  overrides:")?;
        }
        overridden.try_for_each(|step| field_line(f, 4, step))
    }
}

// ---- Nested ----

/// What a layer did to a [`Nested`] document or a [`Keyed`] item
/// ([`Explanation::actions`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Action {
    /// Brought in where nothing was before.
    Added,
    /// Brought back after an omit.
    Restored,
    /// Patched on top of the inherited document.
    Modified,
    /// The inherited document dropped and replaced.
    Replaced,
    /// Explicitly removed.
    Omitted,
    /// Dropped by a layer that replaced a container without it.
    Cleared,
    /// Removed with a container the layer omitted.
    Removed,
}

impl Action {
    /// Lower-case name: `added`, `restored`, `modified`, `replaced`,
    /// `omitted`, `cleared` or `removed`.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Added => "added",
            Self::Restored => "restored",
            Self::Modified => "modified",
            Self::Replaced => "replaced",
            Self::Omitted => "omitted",
            Self::Cleared => "cleared",
            Self::Removed => "removed",
        }
    }

    /// `true` if the document is present after this action.
    #[must_use]
    pub const fn is_present(self) -> bool {
        matches!(
            self,
            Self::Added | Self::Restored | Self::Modified | Self::Replaced
        )
    }
}

/// The name, as [`Action::as_str`].
impl fmt::Display for Action {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

impl<'a, P> Explanation<'a, Nested<P>> {
    /// What each layer did, strongest first.
    #[must_use]
    pub fn actions(&self) -> Vec<(&Step<'a, Nested<P>>, Action)> {
        let mut last: Option<Action> = None;
        let mut out = Vec::with_capacity(self.steps.len());
        for step in &self.steps {
            let present = last.is_some_and(Action::is_present);
            let gone = matches!(last, Some(Action::Omitted | Action::Removed));
            let action = match (&step.change, step.change.leaf()) {
                (Change::Removed { .. }, _) => Action::Removed,
                (_, Some(Nested::Omit)) => Action::Omitted,
                (_, Some(Nested::Unset) | None) => Action::Cleared,
                (Change::Apply(_), Some(Nested::Patch(_))) if present => Action::Modified,
                _ if present => Action::Replaced,
                _ if gone => Action::Restored,
                _ => Action::Added,
            };
            out.push((step, action));
            last = Some(action);
        }
        out.reverse();
        out
    }

    /// `true` if the document is present once every layer is applied.
    #[must_use]
    pub fn is_present(&self) -> bool {
        self.actions()
            .first()
            .is_some_and(|(_, action)| action.is_present())
    }

    /// One word for the resolved state: `present`, `omitted`, `unset`
    /// (cleared), `absent` (removed with a container) or `not mentioned`.
    fn status(actions: &[(&Step<'a, Nested<P>>, Action)]) -> &'static str {
        match actions.first().map(|(_, action)| *action) {
            None => "not mentioned",
            Some(Action::Omitted) => "omitted",
            Some(Action::Cleared) => "unset",
            Some(Action::Removed) => "absent",
            Some(_) => "present",
        }
    }

    /// The report, `head` first, each action indented by `indent`.
    fn write(&self, f: &mut fmt::Formatter<'_>, head: &str, indent: usize) -> fmt::Result {
        let actions = self.actions();
        write!(f, "{head}: {}", Self::status(&actions))?;
        actions
            .iter()
            .try_for_each(|(step, action)| line(f, indent, step, action))
    }
}

/// `path: status`, then each layer's action, strongest first.
impl<P> fmt::Display for Explanation<'_, Nested<P>> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.write(f, display_path(&self.path), 2)
    }
}

// ---- Keyed ----

impl<'a, K: PartialEq + fmt::Debug, P> Explanation<'a, Keyed<K, P>> {
    /// Every key of the resolved list, in list order, omitted and unset
    /// entries included ([`Keyed::entries`]).
    #[must_use]
    pub fn keys(&self) -> Vec<&'a K> {
        let mut keys: Vec<&'a K> = Vec::new();
        for step in &self.steps {
            if !matches!(step.change, Change::Apply(_)) {
                keys.clear();
            }
            for (key, _) in step.change.leaf().into_iter().flat_map(Keyed::entries) {
                if !keys.contains(&key) {
                    keys.push(key);
                }
            }
        }
        keys
    }

    /// The explanation of the item for `key`: the same as explaining the
    /// path [`key`](FieldPath::key)`(key)` directly.
    #[must_use]
    pub fn item(&self, key: &K) -> Explanation<'a, Nested<P>> {
        let steps = self
            .steps
            .iter()
            .filter_map(|step| {
                let change = match &step.change {
                    Change::Apply(list) => Change::Apply(list.get(key).filter(|n| !n.is_unset())?),
                    Change::Reset { by, leaf } => Change::Reset {
                        by: Arc::clone(by),
                        leaf: leaf.and_then(|list| list.get(key)),
                    },
                    Change::Removed { by } => Change::Removed { by: Arc::clone(by) },
                };
                Some(Step {
                    layer: step.layer,
                    change,
                })
            })
            .collect();
        Explanation {
            path: format!("{}[{key:?}]", self.path).into(),
            steps,
        }
    }
}

/// `path: N entries`, then each entry's status and actions, in list order.
impl<K: PartialEq + fmt::Debug, P> fmt::Display for Explanation<'_, Keyed<K, P>> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let keys = self.keys();
        write!(f, "{}: {} entries", display_path(&self.path), keys.len())?;
        for key in keys {
            f.write_str("\n  ")?;
            self.item(key).write(f, &format!("[{key:?}]"), 4)?;
        }
        Ok(())
    }
}

// ---- Appended ----

impl<'a, T> Explanation<'a, Appended<T>> {
    /// Where the resolved list starts: the strongest step that drops the
    /// inherited list (a replace, or a replaced or omitted container), or
    /// the weakest step.
    fn boundary(&self) -> usize {
        self.steps
            .iter()
            .rposition(|step| match step.change {
                Change::Apply(list) => list.replaces(),
                Change::Reset { .. } | Change::Removed { .. } => true,
            })
            .unwrap_or(0)
    }

    /// The steps the resolved list is made of, strongest first: the
    /// boundary (the replace it starts from, if any) and every append above
    /// it.
    pub fn live(&self) -> impl Iterator<Item = &Step<'a, Appended<T>>> {
        self.steps[self.boundary()..].iter().rev()
    }

    /// The steps whose items a replace dropped, strongest first.
    pub fn dropped(&self) -> impl Iterator<Item = &Step<'a, Appended<T>>> {
        self.steps[..self.boundary()].iter().rev()
    }

    /// The resolved list: every [`live`](Self::live) step's items, weakest
    /// first.
    #[must_use]
    pub fn items(&self) -> Vec<&'a T> {
        self.steps[self.boundary()..]
            .iter()
            .filter_map(|step| step.change.leaf())
            .flat_map(Appended::items)
            .collect()
    }
}

/// One step of an [`Appended`]: `appended [..]`, `replaced with [..]`,
/// `set to [..]` (by a replaced container), `cleared` or `removed`.
fn appended_line<T: fmt::Debug>(
    f: &mut fmt::Formatter<'_>,
    indent: usize,
    step: &Step<'_, Appended<T>>,
) -> fmt::Result {
    let items = step.change.leaf().map_or(&[][..], Appended::items);
    match &step.change {
        Change::Removed { .. } => line(f, indent, step, "removed"),
        Change::Reset { .. } if items.is_empty() => line(f, indent, step, "cleared"),
        Change::Reset { .. } => line(f, indent, step, format_args!("set to {items:?}")),
        Change::Apply(list) if list.replaces() => {
            line(f, indent, step, format_args!("replaced with {items:?}"))
        }
        Change::Apply(_) => line(f, indent, step, format_args!("appended {items:?}")),
    }
}

/// `path = [..]`, then the live steps and the dropped ones, strongest first.
impl<T: fmt::Debug> fmt::Display for Explanation<'_, Appended<T>> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} = {:?}", display_path(&self.path), self.items())?;
        if self.steps.is_empty() {
            return f.write_str("\n  not set by any layer");
        }
        self.live().try_for_each(|step| appended_line(f, 2, step))?;
        let mut dropped = self.dropped().peekable();
        if dropped.peek().is_some() {
            f.write_str("\n  dropped:")?;
        }
        dropped.try_for_each(|step| appended_line(f, 4, step))
    }
}
