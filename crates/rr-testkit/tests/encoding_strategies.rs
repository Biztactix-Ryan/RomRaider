//! The Encoding strategies (`rr_testkit::strategies::encoding`) and the
//! reference cross-check (`rr_testkit::encoding_oracle`), US-RR-19-12.
//!
//! * Coverage, checked deterministically rather than hoped for: the shape list
//!   is exactly the set of combinations `Encoding::new` accepts; every shape
//!   (so every storage, both byte orders, no / unsigned / signed bitfield and
//!   both layouts) is generated; bitfield masks reach their edge forms; values
//!   reach their extremes and every float class; bytes reach their edge forms.
//! * Smoke properties: generated values round-trip through rr-core and agree
//!   with the reference codec, generated bytes decode the same in both,
//!   invalid values are refused by both, Bosch-subtract cells are refused by
//!   both. The full property test is US-RR-19-1.

use std::collections::{BTreeSet, HashSet};

use proptest::prelude::*;
use proptest::strategy::{Strategy, ValueTree};
use proptest::test_runner::TestRunner;
use rr_core::encoding::{BitField, Encoding, FloatClass, Layout, Raw, Storage};
use rr_testkit::encoding_oracle::{
    self, Refusal, assert_agrees_with_reference, assert_bytes_agree_with_reference, check_bytes,
    check_value,
};
use rr_testkit::strategies::encoding::{
    ENDIANS, EncodingShape, F32_EDGE_BITS, F64_EDGE_BITS, FieldKind, LAYOUTS, any_encoding,
    bosch_subtract_encoding, bytes_for, cell_encoding, encoding_in, encoding_shapes,
    invalid_value_for, signed_bitfield, table_bytes_for, unsigned_bitfield, value_for,
};

/// `n` values of `strategy` from a deterministic runner.
#[expect(
    clippy::unwrap_used,
    reason = "test-only helper outside a #[test] fn; panicking is how it fails the calling test"
)]
fn sample<S: Strategy>(strategy: &S, n: usize) -> Vec<S::Value> {
    let mut runner = TestRunner::deterministic();
    (0..n)
        .map(|_| strategy.new_tree(&mut runner).unwrap().current())
        .collect()
}

/// A bitfield of `kind` that fits every integer storage.
#[expect(
    clippy::unwrap_used,
    reason = "test-only helper outside a #[test] fn; panicking is how it fails the calling test"
)]
fn representative(kind: FieldKind) -> Option<BitField> {
    match kind {
        FieldKind::Whole => None,
        FieldKind::Unsigned => Some(BitField::new(0b1, None, false).unwrap()),
        FieldKind::Signed => Some(BitField::new(0b11, None, true).unwrap()),
    }
}

