#[test]
fn the_shape_list_is_exactly_what_encoding_new_accepts() {
    let shapes: HashSet<EncodingShape> = encoding_shapes().into_iter().collect();
    assert_eq!(shapes.len(), encoding_shapes().len(), "no duplicate shapes");
    let mut product = 0;
    for storage in Storage::ALL {
        for endian in ENDIANS {
            for field in FieldKind::ALL {
                for layout in LAYOUTS {
                    product += 1;
                    let shape = EncodingShape {
                        storage,
                        endian,
                        field,
                        layout,
                    };
                    let accepted =
                        Encoding::new(storage, endian, representative(field), layout).is_ok();
                    assert_eq!(accepted, shape.is_valid(), "{shape:?}");
                    assert_eq!(accepted, shapes.contains(&shape), "{shape:?}");
                }
            }
        }
    }
    assert_eq!(product, 13 * 2 * 3 * 2);
    // u20: big only; floats: no bitfield, no Bosch; u20: no Bosch.
    // Default: 21 integer storage/endian pairs x 3 + 4 float pairs = 67;
    // Bosch: 20 pairs (no u20) x 3 = 60.
    assert_eq!(shapes.len(), 67 + 60);
}

#[test]
fn every_shape_generates_encodings_of_that_shape() {
    for shape in encoding_shapes() {
        for encoding in sample(&encoding_in(shape), 16) {
            assert_eq!(EncodingShape::of(encoding), shape);
        }
    }
}

#[test]
fn any_encoding_reaches_every_shape_storage_endian_field_and_layout() {
    let all: HashSet<EncodingShape> = encoding_shapes().into_iter().collect();
    let seen: HashSet<EncodingShape> = sample(&any_encoding(), 4000)
        .into_iter()
        .map(EncodingShape::of)
        .collect();
    assert_eq!(
        seen,
        all,
        "missed: {:?}",
        all.difference(&seen).collect::<Vec<_>>()
    );
    let storages: HashSet<Storage> = seen.iter().map(|s| s.storage).collect();
    assert_eq!(storages.len(), Storage::ALL.len());
    assert_eq!(
        seen.iter().map(|s| s.endian).collect::<HashSet<_>>().len(),
        2
    );
    assert_eq!(
        seen.iter().map(|s| s.field).collect::<HashSet<_>>().len(),
        3
    );
    assert_eq!(
        seen.iter().map(|s| s.layout).collect::<HashSet<_>>().len(),
        2
    );

    let cells: HashSet<EncodingShape> =
        all.iter().copied().filter(|s| s.is_single_cell()).collect();
    let seen_cells: HashSet<EncodingShape> = sample(&cell_encoding(), 3000)
        .into_iter()
        .map(EncodingShape::of)
        .collect();
    assert_eq!(seen_cells, cells);
    let bosch: HashSet<EncodingShape> = all.difference(&cells).copied().collect();
    let seen_bosch: HashSet<EncodingShape> = sample(&bosch_subtract_encoding(), 3000)
        .into_iter()
        .map(EncodingShape::of)
        .collect();
    assert_eq!(seen_bosch, bosch);
}

#[test]
fn bitfields_reach_their_edge_forms() {
    for storage in Storage::ALL.into_iter().filter(|s| s.is_integer()) {
        let bits = storage.value_bits();
        let full = u64::MAX >> (64 - bits);
        let unsigned = sample(&unsigned_bitfield(storage), 600);
        let signed = sample(&signed_bitfield(storage), 400);
        for field in unsigned.iter().chain(&signed) {
            assert!(field.reach_bits() <= bits, "{storage}: {field:?}");
            assert!(field.shift() <= field.mask().trailing_zeros());
        }
        let contiguous = |m: u64| {
            let run = m >> m.trailing_zeros();
            run & run.wrapping_add(1) == 0
        };
        let has = |fields: &[BitField], what: &str, p: &dyn Fn(&BitField) -> bool| {
            assert!(fields.iter().any(p), "{storage}: no {what}");
        };
        has(&unsigned, "full-width mask", &|f| f.mask() == full);
        has(&unsigned, "single top bit", &|f| {
            f.mask() == 1 << (bits - 1)
        });
        has(&unsigned, "bit 0 only", &|f| f.mask() == 1);
        has(&unsigned, "non-contiguous mask", &|f| !contiguous(f.mask()));
        has(&unsigned, "shift below trailing zeros", &|f| {
            f.shift() < f.mask().trailing_zeros()
        });
        has(&unsigned, "shift = trailing zeros > 0", &|f| {
            f.shift() > 0 && f.shift() == f.mask().trailing_zeros()
        });
        assert!(signed.iter().all(|f| f.is_signed() && contiguous(f.mask())));
        assert!(unsigned.iter().all(|f| !f.is_signed()));
        has(&signed, "full-width signed field", &|f| f.mask() == full);
        has(&signed, "2-bit signed field", &|f| {
            f.mask().count_ones() == 2
        });
        has(&signed, "signed shift below trailing zeros", &|f| {
            f.shift() < f.mask().trailing_zeros()
        });
    }
}

#[test]
fn the_float_edge_patterns_cover_every_class_and_sign() {
    let f32_classes: BTreeSet<(bool, String)> = F32_EDGE_BITS
        .iter()
        .map(|b| (b >> 31 == 1, FloatClass::of_f32_bits(*b).name().to_owned()))
        .collect();
    let f64_classes: BTreeSet<(bool, String)> = F64_EDGE_BITS
        .iter()
        .map(|b| (b >> 63 == 1, FloatClass::of_f64_bits(*b).name().to_owned()))
        .collect();
    let classes = [
        "zero",
        "subnormal",
        "normal",
        "infinite",
        "quiet NaN",
        "signalling NaN",
    ];
    for negative in [false, true] {
        for class in classes {
            let key = (negative, class.to_owned());
            assert!(f32_classes.contains(&key), "f32 {key:?}");
            assert!(f64_classes.contains(&key), "f64 {key:?}");
        }
    }
}

/// Integer range `(min, max)` of an encoding, computed here from the codec's
/// documented rules (not from the strategy).
#[expect(
    clippy::unwrap_used,
    reason = "test-only helper outside a #[test] fn; panicking is how it fails the calling test"
)]
fn int_bounds(encoding: Encoding) -> (i128, i128) {
    let (min, max) = encoding.storage().int_range().unwrap();
    let Some(field) = encoding.bitfield() else {
        return (min, max);
    };
    let lowest = field.mask().trailing_zeros();
    let step = 1_i128 << (lowest - field.shift());
    let bits = field.mask() >> lowest;
    if field.is_signed() {
        let half = 1_i128 << (bits.count_ones() - 1);
        (-half * step, (half - 1) * step)
    } else {
        (0, i128::from(bits) * step)
    }
}

#[test]
fn values_reach_the_extremes_of_every_cell_encoding() {
    let mut runner = TestRunner::deterministic();
    for shape in encoding_shapes().into_iter().filter(|s| s.is_single_cell()) {
        for _ in 0..8 {
            let encoding = encoding_in(shape).new_tree(&mut runner).unwrap().current();
            let values = sample(&value_for(&encoding), 300);
            for raw in &values {
                // Every generated value is storable.
                assert!(encoding.encode(*raw).is_ok(), "{encoding:?}: {raw:?}");
            }
            if encoding.storage().is_float() {
                let classes: HashSet<FloatClass> =
                    values.iter().filter_map(|r| r.float_class()).collect();
                assert_eq!(classes.len(), 6, "{encoding:?}: {classes:?}");
                continue;
            }
            let ints: HashSet<i128> = values
                .iter()
                .map(|r| match r {
                    Raw::Int(v) => *v,
                    other => panic!("{encoding:?}: {other:?}"),
                })
                .collect();
            let (min, max) = int_bounds(encoding);
            assert!(ints.contains(&min), "{encoding:?}: min {min} not reached");
            assert!(ints.contains(&max), "{encoding:?}: max {max} not reached");
            assert!(ints.contains(&0), "{encoding:?}: 0 not reached");
            let field_bits = encoding.bitfield().map_or(64, |f| f.mask().count_ones());
            let possible = 1_usize << field_bits.min(8);
            assert!(
                ints.len() >= possible.min(8),
                "{encoding:?}: only {} distinct values",
                ints.len()
            );
        }
    }
}

#[test]
fn bytes_and_tables_have_the_cell_width() {
    for encoding in sample(&any_encoding(), 300) {
        let width = encoding.storage().cell_bytes();
        for bytes in sample(&bytes_for(&encoding), 20) {
            assert_eq!(bytes.len(), width);
        }
        for table in sample(&table_bytes_for(&encoding, 1..=6), 10) {
            assert_eq!(table.len() % width, 0);
            assert!((1..=6).contains(&(table.len() / width)));
        }
    }
    let f64 = Encoding::new(
        Storage::F64,
        rr_core::encoding::Endian::Little,
        None,
        Layout::Default,
    )
    .unwrap();
    let patterns: HashSet<Vec<u8>> = sample(&bytes_for(&f64), 400).into_iter().collect();
    assert!(patterns.contains(&vec![0xFF; 8]));
    assert!(patterns.contains(&vec![0; 8]));
    // The signalling NaN 0x7FF0_0000_0000_0001, little-endian.
    assert!(patterns.contains(&vec![1, 0, 0, 0, 0, 0, 0xF0, 0x7F]));
}

