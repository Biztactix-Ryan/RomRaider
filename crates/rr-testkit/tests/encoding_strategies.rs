#[test]
fn the_oracle_handles_signed_fields_float_bits_and_refusals() {
    // The reference reads fields unsigned; the oracle sign-extends them.
    let signed = Encoding::new(
        Storage::U8,
        rr_core::encoding::Endian::Big,
        Some(BitField::new(0xF0, None, true).unwrap()),
        Layout::Default,
    )
    .unwrap();
    // rr-core decodes 0x80 in the high nibble as -8; so does the oracle.
    assert_eq!(
        encoding_oracle::check_decode(signed, &[0x80]).unwrap(),
        Ok(Raw::Int(-8))
    );
    assert_eq!(
        assert_agrees_with_reference(signed, Raw::Int(-8), &[0x05]),
        Ok(vec![0x85])
    );
    assert_eq!(
        assert_agrees_with_reference(signed, Raw::Int(8), &[0x05]),
        Err(Refusal::BitFieldOutOfRange)
    );
    // NaN payloads are compared bit-exactly.
    assert!(!encoding_oracle::same_bits(
        Raw::F32(f32::from_bits(0x7FC0_0000)),
        Raw::F32(f32::from_bits(0x7FC0_0001))
    ));
    assert!(encoding_oracle::same_bits(
        Raw::F64(f64::from_bits(0x7FF0_0000_0000_0001)),
        Raw::F64(f64::from_bits(0x7FF0_0000_0000_0001))
    ));
    assert!(!encoding_oracle::same_bits(Raw::F32(0.0), Raw::F32(-0.0)));
    assert!(!encoding_oracle::same_bits(Raw::F32(1.0), Raw::F64(1.0)));
    // A short buffer is refused by both before the value is looked at.
    assert_eq!(
        check_value(signed, Raw::Int(100), &[]).unwrap(),
        Err(Refusal::ShortInput)
    );
    // A Disagreement names the encoding and the detail.
    let disagreement = encoding_oracle::Disagreement {
        encoding: signed,
        detail: "x".to_owned(),
    };
    assert!(disagreement.to_string().contains("disagree"));
}

#[test]
fn the_reference_table_hook_decodes_a_bosch_table() {
    let encoding = Encoding::new(
        Storage::U8,
        rr_core::encoding::Endian::Big,
        None,
        Layout::BoschSubtract,
    )
    .unwrap();
    // value[i] = 256 - (s[i] + ... + s[N-1]).
    assert_eq!(
        encoding_oracle::reference_decode_table(encoding, &[1, 2, 3]).unwrap(),
        vec![Raw::Int(250), Raw::Int(251), Raw::Int(253)]
    );
}

// ---------------------------------------------------------------------------
// Smoke properties (the full property test is US-RR-19-1)
// ---------------------------------------------------------------------------

proptest! {
    #![proptest_config(ProptestConfig::with_cases(1024))]

    #[test]
    fn values_round_trip_and_agree_with_the_reference(
        (encoding, raw, start) in cell_encoding()
            .prop_flat_map(|e| (Just(e), value_for(&e), bytes_for(&e))),
    ) {
        let written = check_value(encoding, raw, &start);
        prop_assert!(matches!(written, Ok(Ok(_))), "{written:?}");
    }

    #[test]
    fn bytes_decode_the_same_and_write_back(
        (encoding, bytes) in cell_encoding().prop_flat_map(|e| (Just(e), bytes_for(&e))),
    ) {
        let decoded = check_bytes(encoding, &bytes);
        prop_assert!(matches!(decoded, Ok(Ok(_))), "{decoded:?}");
    }

    #[test]
    fn invalid_values_are_refused_by_both(
        (encoding, raw, start) in cell_encoding()
            .prop_flat_map(|e| (Just(e), invalid_value_for(&e), bytes_for(&e))),
    ) {
        let refused = check_value(encoding, raw, &start);
        prop_assert!(
            matches!(
                refused,
                Ok(Err(Refusal::OutOfRange | Refusal::BitFieldOutOfRange | Refusal::KindMismatch))
            ),
            "{raw:?}: {refused:?}"
        );
    }

    #[test]
    fn bosch_subtract_cells_are_refused_by_both(
        (encoding, bytes, raw) in bosch_subtract_encoding()
            .prop_flat_map(|e| (Just(e), bytes_for(&e), value_for(&e))),
    ) {
        prop_assert_eq!(assert_bytes_agree_with_reference(encoding, &bytes), Err(Refusal::WholeTable));
        prop_assert_eq!(
            assert_agrees_with_reference(encoding, raw, &bytes),
            Err(Refusal::WholeTable)
        );
    }
}
