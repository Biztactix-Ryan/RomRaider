//! Lint self-test (`cargo xtask lint-selftest`): proves the safety lints fire.
//!
//! Proves US-RR-3-1 (a test crate calling `std::thread::sleep` or
//! `Instant::now` outside RealClock fails clippy in CI) and US-RR-3-2
//! (`unwrap()` / `expect()` in non-test library code fails clippy), and backs
//! US-RR-18-4 (only RealClock may call std time APIs).
//!
//! Reading `clippy.toml` and `Cargo.toml` proves nothing about what clippy
//! actually does with them, so this runs clippy for real. It generates a
//! throwaway fixture workspace under `<root>/target/lint-selftest/` that is
//! configured exactly like the real one:
//!
//! * the fixture's `[workspace.lints]` table is the real root `Cargo.toml`'s
//!   `[workspace.lints]`, copied verbatim, and each fixture crate inherits it
//!   with `[lints] workspace = true`, like every real crate;
//! * the real `clippy.toml` and `rust-toolchain.toml` are copied byte for byte;
//! * clippy runs with the CI job's arguments (`--workspace --all-targets --
//!   -D warnings`), plus `--keep-going` so one failing crate does not hide
//!   the diagnostics of the other.
//!
//! The fixture sources ([`FIXTURE_FILES`]) plant one violation per line and
//! mark it `//~ clippy::<lint>`. The self-test passes only when clippy exits
//! with failure, every marked line got exactly its lint, and nothing else was
//! reported. In particular `unwrap()` / `expect()` / `panic!` inside
//! `#[cfg(test)]` and `#[test]` code are planted *unmarked*, so a lint that
//! fired there (tests would no longer compile) also fails the self-test.
//!
//! Removing a ban from `clippy.toml`, lowering a lint in `Cargo.toml`, or
//! deleting the `-in-tests` switches therefore makes this fail with
//! "expected lint ... did not fire" or "unexpected diagnostic".

use std::collections::BTreeSet;
use std::fmt;
use std::fs;
use std::io::BufReader;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use anyhow::{Context as _, Result, bail};
use cargo_metadata::Message;

/// Fixture directory, relative to the workspace root (inside `target/`, so it
/// is never committed and never scanned by the other xtask checks).
pub const FIXTURE_DIR: &str = "target/lint-selftest";

/// Marker that ends a fixture line whose violation must be reported.
pub const MARKER: &str = "//~ ";

/// Fixture crates (workspace members of the generated fixture).
pub const FIXTURE_MEMBERS: &[&str] = &["planted-lib", "planted-tests"];

/// Fixture sources: `(path relative to the fixture root, contents)`.
