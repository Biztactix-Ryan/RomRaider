/// One lint diagnostic at a source line of the fixture.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Hit {
    /// Path relative to the fixture root, `/`-separated.
    pub path: String,
    /// 1-based line.
    pub line: usize,
    /// Lint name as clippy reports it, e.g. `clippy::unwrap_used`.
    pub lint: String,
}

impl fmt::Display for Hit {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}: {}", self.path, self.line, self.lint)
    }
}

/// Why the self-test failed.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum Problem {
    /// A marked violation that clippy did not report.
    Missing(Hit),
    /// A diagnostic on a line not marked for it.
    Unexpected(Hit),
    /// Clippy exited successfully, so CI would have passed.
    ClippyPassed,
}

impl fmt::Display for Problem {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Missing(h) => write!(
                f,
                "{}:{}: expected lint {} did not fire",
                h.path, h.line, h.lint
            ),
            Self::Unexpected(h) => write!(f, "unexpected diagnostic {h}"),
            Self::ClippyPassed => f.write_str(
                "cargo clippy succeeded on planted violations: CI would not fail on them",
            ),
        }
    }
}

/// The `//~ <lint>` markers in the fixture sources: what clippy must report.
#[must_use]
pub fn expected_hits(files: &[(&str, &str)]) -> BTreeSet<Hit> {
    let mut out = BTreeSet::new();
    for (path, src) in files {
        for (i, line) in src.lines().enumerate() {
            if let Some((_, lint)) = line.split_once(MARKER) {
                out.insert(Hit {
                    path: (*path).to_owned(),
                    line: i + 1,
                    lint: lint.trim().to_owned(),
                });
            }
        }
    }
    out
}

/// Compare what clippy reported with what was planted.
#[must_use]
pub fn evaluate(
    expected: &BTreeSet<Hit>,
    got: &BTreeSet<Hit>,
    clippy_succeeded: bool,
) -> Vec<Problem> {
    let mut problems: Vec<Problem> = expected
        .difference(got)
        .cloned()
        .map(Problem::Missing)
        .chain(got.difference(expected).cloned().map(Problem::Unexpected))
        .collect();
    if clippy_succeeded {
        problems.push(Problem::ClippyPassed);
    }
    problems
}

/// Turn one diagnostic into a [`Hit`], keyed by its primary span.
///
/// Returns `None` for summary lines ("aborting due to N previous errors"),
/// which have no span. A diagnostic without a lint code (a plain compile
/// error) is kept with the lint `<no code>`, so it shows up as unexpected.
fn hit_of(diag: &cargo_metadata::diagnostic::Diagnostic, fixture: &Path) -> Option<Hit> {
    let span = diag
        .spans
        .iter()
        .find(|s| s.is_primary)
        .or_else(|| diag.spans.first())?;
    let file = Path::new(&span.file_name);
    let rel = file.strip_prefix(fixture).unwrap_or(file);
    let path = rel
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("/");
    let lint = diag
        .code
        .as_ref()
        .map_or_else(|| "<no code>".to_owned(), |c| c.code.clone());
    Some(Hit {
        path,
        line: span.line_start,
        lint,
    })
}

/// Write the fixture workspace for `root` into `fixture`, replacing any old one.
pub fn write_fixture(root: &Path, fixture: &Path) -> Result<()> {
    let manifest_path = root.join("Cargo.toml");
    let manifest_text = fs::read_to_string(&manifest_path)
        .with_context(|| format!("reading {}", manifest_path.display()))?;
    let manifest: toml::Table = toml::from_str(&manifest_text)
        .with_context(|| format!("parsing {}", manifest_path.display()))?;
    let ws = manifest
        .get("workspace")
        .and_then(toml::Value::as_table)
        .context("root Cargo.toml has no [workspace]")?;
    let lints = ws
        .get("lints")
        .cloned()
        .context("root Cargo.toml has no [workspace.lints]")?;
    let edition = ws
        .get("package")
        .and_then(|p| p.get("edition"))
        .cloned()
        .unwrap_or_else(|| toml::Value::String("2024".to_owned()));

    let mut fixture_ws = toml::Table::new();
    fixture_ws.insert("resolver".to_owned(), "3".into());
    fixture_ws.insert(
        "members".to_owned(),
        toml::Value::Array(FIXTURE_MEMBERS.iter().map(|m| (*m).into()).collect()),
    );
    let mut pkg = toml::Table::new();
    pkg.insert("edition".to_owned(), edition);
    fixture_ws.insert("package".to_owned(), toml::Value::Table(pkg));
    fixture_ws.insert("lints".to_owned(), lints);
    let mut fixture_manifest = toml::Table::new();
    fixture_manifest.insert("workspace".to_owned(), toml::Value::Table(fixture_ws));

    if fixture.exists() {
        // Keep `target/` (incremental build cache); replace everything else.
        for entry in
            fs::read_dir(fixture).with_context(|| format!("reading {}", fixture.display()))?
        {
            let entry = entry?;
            if entry.file_name() == "target" {
                continue;
            }
            let p = entry.path();
            if entry.file_type()?.is_dir() {
                fs::remove_dir_all(&p)
            } else {
                fs::remove_file(&p)
            }
            .with_context(|| format!("removing {}", p.display()))?;
        }
    }
    fs::create_dir_all(fixture).with_context(|| format!("creating {}", fixture.display()))?;
    let header = "# Generated by `cargo xtask lint-selftest` from the workspace root \
                  Cargo.toml [workspace.lints]. Do not edit.\n";
    write(
        &fixture.join("Cargo.toml"),
        &format!("{header}{}", toml::to_string(&fixture_manifest)?),
    )?;
    for name in ["clippy.toml", "rust-toolchain.toml"] {
        let src = root.join(name);
        if name == "clippy.toml" || src.is_file() {
            fs::copy(&src, fixture.join(name))
                .with_context(|| format!("copying {}", src.display()))?;
        }
    }
    for member in FIXTURE_MEMBERS {
        write(
            &fixture.join(member).join("Cargo.toml"),
            &format!(
                "[package]\nname = \"{member}\"\nversion = \"0.0.0\"\nedition.workspace = true\npublish = false\n\n[lints]\nworkspace = true\n"
            ),
        )?;
    }
    for (rel, src) in FIXTURE_FILES {
        write(&fixture.join(rel), src)?;
    }
    Ok(())
}

fn write(path: &Path, text: &str) -> Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    }
    fs::write(path, text).with_context(|| format!("writing {}", path.display()))
}

/// Outcome of a self-test run.
#[derive(Debug)]
pub struct Report {
    /// The generated fixture workspace.
    pub fixture: PathBuf,
    /// Planted violations (from the markers).
    pub expected: BTreeSet<Hit>,
    /// What clippy reported.
    pub got: BTreeSet<Hit>,
    /// What makes the self-test fail (empty = pass).
    pub problems: Vec<Problem>,
}

/// Generate the fixture for `root`, run clippy on it, and compare.
pub fn run(root: &Path) -> Result<Report> {
    if !root.join("Cargo.toml").is_file() {
        bail!("{} is not a workspace root (no Cargo.toml)", root.display());
    }
    let fixture = root.join(FIXTURE_DIR);
    write_fixture(root, &fixture)?;
    let fixture = fixture
        .canonicalize()
        .with_context(|| format!("resolving {}", fixture.display()))?;

    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let mut cmd = Command::new(cargo);
    cmd.current_dir(&fixture)
        .args([
            "clippy",
            "--workspace",
            "--all-targets",
            "--keep-going",
            "--message-format=json",
            "--",
            "-D",
            "warnings",
        ])
        // Own target dir, so this never contends with the main build.
        .env("CARGO_TARGET_DIR", fixture.join("target"))
        // Only the copied clippy.toml may configure clippy.
        .env_remove("CLIPPY_CONF_DIR")
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    let mut child = cmd.spawn().context("spawning cargo clippy")?;
    let stdout = child.stdout.take().context("cargo clippy stdout")?;
    let mut got = BTreeSet::new();
    for msg in Message::parse_stream(BufReader::new(stdout)) {
        if let Message::CompilerMessage(m) = msg.context("reading cargo clippy output")? {
            got.extend(hit_of(&m.message, &fixture));
        }
    }
    let output = child
        .wait_with_output()
        .context("waiting for cargo clippy")?;
    if got.is_empty() && !output.status.success() {
        bail!(
            "cargo clippy failed without reporting any diagnostic:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let expected = expected_hits(FIXTURE_FILES);
    let problems = evaluate(&expected, &got, output.status.success());
    Ok(Report {
        fixture,
        expected,
        got,
        problems,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hit(path: &str, line: usize, lint: &str) -> Hit {
        Hit {
            path: path.to_owned(),
            line,
            lint: lint.to_owned(),
        }
    }

    fn lines_with(lint: &str, path: &str) -> Vec<usize> {
        expected_hits(FIXTURE_FILES)
            .into_iter()
            .filter(|h| h.lint == lint && h.path == path)
            .map(|h| h.line)
            .collect()
    }

    fn src(path: &str) -> &'static str {
        FIXTURE_FILES
            .iter()
            .find(|(p, _)| *p == path)
            .map(|(_, s)| *s)
            .unwrap()
    }

    fn line(path: &str, n: usize) -> &'static str {
        src(path).lines().nth(n - 1).unwrap()
    }

    /// The fixture plants each case US-RR-3-1 / US-RR-3-2 needs, marked.
    #[test]
    fn fixture_plants_every_required_case() {
        let lib = "planted-lib/src/lib.rs";
        let itest = "planted-tests/tests/time.rs";
        let banned = |path: &str, needle: &str| {
            lines_with("clippy::disallowed_methods", path)
                .into_iter()
                .any(|n| line(path, n).contains(needle))
        };
        // US-RR-3-1: sleep / Instant::now in library, unit-test and test-crate code.
        for path in [lib, itest] {
            assert!(banned(path, "std::thread::sleep("), "{path}: sleep");
            assert!(banned(path, "Instant::now()"), "{path}: Instant::now");
        }
        assert!(banned(lib, "SystemTime::now()"));
        assert!(banned(lib, "start.elapsed()"));
        assert!(banned(lib, "t.elapsed()"));
        assert!(banned(lib, "nap("), "a renamed import is still caught");
        // US-RR-3-2: unwrap / expect in non-test library code.
        assert_eq!(lines_with("clippy::unwrap_used", lib).len(), 2);
        assert_eq!(lines_with("clippy::expect_used", lib).len(), 2);
        // ... and unmarked (must not fire) inside #[cfg(test)] / test crates.
        let cfg_test = src(lib).find("#[cfg(test)]").unwrap();
        let tests_part = &src(lib)[cfg_test..];
        assert!(tests_part.contains(".unwrap()") && tests_part.contains(".expect(\"ok\")"));
        for (n, l) in src(lib).lines().enumerate() {
            if l.contains(".unwrap()") || l.contains(".expect(") {
                let in_tests = src(lib)[..cfg_test].lines().count() <= n;
                assert_eq!(l.contains(MARKER), !in_tests, "line {}: {l}", n + 1);
            }
        }
        assert!(src(itest).contains("u8::try_from(1u32).unwrap()"));
    }

    #[test]
    fn markers_are_parsed_with_path_line_and_lint() {
        let files = [(
            "a/src/lib.rs",
            "fn f() {}\n    x.unwrap() //~ clippy::unwrap_used\n",
        )];
        let got = expected_hits(&files);
        assert_eq!(
            got.into_iter().collect::<Vec<_>>(),
            vec![hit("a/src/lib.rs", 2, "clippy::unwrap_used")]
        );
    }

    #[test]
    fn all_expected_and_clippy_failed_passes() {
        let e: BTreeSet<_> = [hit("a.rs", 1, "clippy::unwrap_used")].into();
        assert!(evaluate(&e, &e.clone(), false).is_empty());
    }

    /// The self-test's own failure mode: a planted violation that clippy no
    /// longer reports (lint removed or lowered) fails it.
    #[test]
    fn lint_that_did_not_fire_fails() {
        let e: BTreeSet<_> = [
            hit("a.rs", 1, "clippy::unwrap_used"),
            hit("a.rs", 2, "clippy::disallowed_methods"),
        ]
        .into();
        let got: BTreeSet<_> = [hit("a.rs", 1, "clippy::unwrap_used")].into();
        let p = evaluate(&e, &got, false);
        assert_eq!(
            p,
            vec![Problem::Missing(hit(
                "a.rs",
                2,
                "clippy::disallowed_methods"
            ))]
        );
        assert_eq!(
            p[0].to_string(),
            "a.rs:2: expected lint clippy::disallowed_methods did not fire"
        );
    }

    #[test]
    fn diagnostic_on_unmarked_line_fails() {
        let e: BTreeSet<_> = [hit("a.rs", 1, "clippy::unwrap_used")].into();
        let got: BTreeSet<_> = [
            hit("a.rs", 1, "clippy::unwrap_used"),
            hit("a.rs", 9, "clippy::unwrap_used"),
        ]
        .into();
        assert_eq!(
            evaluate(&e, &got, false),
            vec![Problem::Unexpected(hit("a.rs", 9, "clippy::unwrap_used"))]
        );
    }

    #[test]
    fn wrong_lint_on_marked_line_fails_both_ways() {
        let e: BTreeSet<_> = [hit("a.rs", 1, "clippy::unwrap_used")].into();
        let got: BTreeSet<_> = [hit("a.rs", 1, "clippy::expect_used")].into();
        assert_eq!(evaluate(&e, &got, false).len(), 2);
    }

    #[test]
    fn clippy_success_fails() {
        let e: BTreeSet<_> = [hit("a.rs", 1, "clippy::unwrap_used")].into();
        assert_eq!(evaluate(&e, &e.clone(), true), vec![Problem::ClippyPassed]);
    }

    #[test]
    fn fixture_manifest_inherits_root_workspace_lints_verbatim() {
        let dir =
            std::env::temp_dir().join(format!("xtask-lint-selftest-unit-{}", std::process::id()));
        let root = dir.join("root");
        fs::create_dir_all(&root).unwrap();
        fs::write(
            root.join("Cargo.toml"),
            "[workspace]\nmembers = []\n[workspace.package]\nedition = \"2024\"\n\
             [workspace.lints.clippy]\nunwrap_used = \"deny\"\nall = { level = \"warn\", priority = -1 }\n",
        )
        .unwrap();
        fs::write(root.join("clippy.toml"), "allow-unwrap-in-tests = true\n").unwrap();
        let fixture = dir.join("fixture");
        write_fixture(&root, &fixture).unwrap();
        let m: toml::Table =
            toml::from_str(&fs::read_to_string(fixture.join("Cargo.toml")).unwrap()).unwrap();
        let clippy = &m["workspace"]["lints"]["clippy"];
        assert_eq!(clippy["unwrap_used"].as_str(), Some("deny"));
        assert_eq!(clippy["all"]["priority"].as_integer(), Some(-1));
        assert_eq!(
            fs::read_to_string(fixture.join("clippy.toml")).unwrap(),
            "allow-unwrap-in-tests = true\n"
        );
        for member in FIXTURE_MEMBERS {
            let t = fs::read_to_string(fixture.join(member).join("Cargo.toml")).unwrap();
            assert!(t.contains("[lints]\nworkspace = true\n"), "{member}");
        }
        let _ = fs::remove_dir_all(&dir);
    }
}
