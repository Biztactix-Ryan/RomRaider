//! Reference-codec isolation check (`cargo xtask check-reference-isolation`).
//!
//! US-RR-10 (PROJECT.md T2(b), D-024): `rr-testkit::reference` is a second,
//! deliberately naive implementation of byte encoding and decoding, used to
//! cross-check `rr-core`'s Encoding. A cross-check is only independent if the
//! reference shares no code with what it checks, so the rule is:
//!
//! **No code reachable from the reference module may name `rr_core`** (or any
//! other workspace crate). That is stronger than "may not import
//! `rr_core::encoding` / `rr_core::expr` / `rr_core::conversion`": the codec must
//! be self-contained, so it has no legitimate use for anything in `rr-core`, and
//! a blanket ban leaves no path-form loophole (`use rr_core::encoding::X`,
//! inline `rr_core::encoding::X`, `use rr_core::{encoding, ..}`,
//! `use rr_core as c; c::encoding`, `use rr_core::*`, `::rr_core::..`,
//! `extern crate rr_core as c;` and the same inside macro bodies all name the
//! `rr_core` token).
//!
//! `rr-testkit` itself depends on `rr-core` for other helpers, so a crate-level
//! rule (`check-deps`) cannot express this; the check is module-level, over the
//! source files of `rr-testkit` plus its manifest (rule 3's dependency aliases):
//!
//! 1. **Scope.** The reference module is [`RULE`]`.module` under
//!    [`RULE`]`.crate_src`: `reference.rs`, `reference/mod.rs` and every `.rs`
//!    file under `reference/`.
//! 2. **Closure over `crate::` / `super::`.** The reference module may use other
//!    `rr-testkit` modules (for example the `kat` fixture types), but then those
//!    modules are checked too, transitively. A path `crate::m..` (or `$crate::m`,
//!    or a `super::` chain that leaves the module's own subtree) pulls top-level
//!    module `m` (`src/m.rs` + `src/m/**`) into the checked set. A path that
//!    names something defined in `lib.rs`, a glob (`crate::*`, `super::*` from
//!    the module root), `crate::{self, ..}` or `crate as c` pulls in the whole
//!    crate. A crate-root macro path (`crate::m!`, `$crate::m!`) is fine when
//!    `m` is defined by a `macro_rules!` in a checked file (its body is
//!    checked) and otherwise pulls in the whole crate.
//!    So a re-export such as `pub use rr_core::encoding as enc;` in
//!    another module is caught as soon as the reference module can reach it.
//! 3. **Forbidden in every checked file:** the identifier of any workspace crate
//!    (`rr_core`, `rr_defs`, ..., from `crates/*/Cargo.toml`); the identifier
//!    of any dependency of the holding crate (`<crate_src>/../Cargo.toml`, every
//!    dependency table, `workspace = true` resolved through the root
//!    `[workspace.dependencies]`) that is a path or git dependency or whose
//!    package is a workspace crate, so renaming the dependency
//!    (`rrc = { package = "rr-core", .. }`) or wrapping rr-core in a local shim
//!    crate that re-exports it does not hide it; `extern crate`
//!    of anything but `std` / `core` / `alloc` (this covers `extern crate self
//!    as x`); `include!` and `#[path = ..]`, also inside `#[cfg_attr(..)]`
//!    (both pull in source this check
//!    cannot see); and an unqualified macro call `m!(..)` unless `m` is a std
//!    macro ([`STD_MACROS`]) or is defined by a `macro_rules!` in a checked file
//!    (a crate-level `#[macro_use]` macro could otherwise expand to `rr_core`
//!    paths unseen). A path-qualified macro (`proptest::prop_assert!`) is
//!    judged by its path like any other path.
//! 4. **No silent vacuity.** With `required: false` an absent module passes,
//!    reporting that it covered nothing (the state before US-RR-10-5 added the
//!    module). Once the module exists, [`RULE`]`.required` must be `true` (the
//!    check fails until it is; it is `true` since US-RR-10-5), and from then
//!    on an absent module fails: renaming or moving the module cannot quietly
//!    turn the rule off.
//!
//! Sources are lexed with `proc-macro2` (syn's tokenizer), so text in comments,
//! doc comments and string literals never matches, while paths inside macro
//! bodies (which a syn AST walk would not see) do. Visibility paths
//! (`pub(crate)`, `pub(super)`, `pub(in crate::x)`) are not uses and are
//! skipped. A file that does not lex is an error (fail closed).
//!
//! Limits, stated plainly: identifiers are matched by name, so a local item
//! named exactly like a workspace crate (`fn rr_core()`) is a false positive —
//! rename it. Inline `mod name { .. }` blocks are tracked for `super::` depth;
//! out-of-line `mod x;` declarations inside an inline `mod` block are not, and
//! a `super::` that escapes from one is seen as staying inside (no such layout
//! exists in rr-testkit). Pulling in a module includes its whole subtree, which
//! can over-report but never under-reports. Code generated by a build script
//! or a proc macro of another crate is not visible (rr-testkit has neither
//! today; a proc-macro crate would itself be a workspace or external crate
//! named in a path, and a workspace one is forbidden by rule 3). Registry
//! dependencies are allowed by name: a crates.io crate cannot depend on this
//! workspace's unpublished, path-only rr-core, so it cannot re-export it.

