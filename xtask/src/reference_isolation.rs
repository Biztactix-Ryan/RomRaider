/// Where the reference module lives and whether it must exist.
#[derive(Debug, Clone, Copy)]
pub struct Rule {
    /// The `src` directory of the crate holding the module, relative to the
    /// workspace root.
    pub crate_src: &'static str,
    /// The top-level module name (`src/<module>.rs`, `src/<module>/`).
    pub module: &'static str,
    /// Whether an absent module is an error. Must be `true` once the module
    /// exists (US-RR-10-5 flips it); see the module docs, rule 4.
    pub required: bool,
}

/// THE rule. `required` is `true` since US-RR-10-5 added the module.
pub const RULE: Rule = Rule {
    crate_src: "crates/rr-testkit/src",
    module: "reference",
    required: true,
};

