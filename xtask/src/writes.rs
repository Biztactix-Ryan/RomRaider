//! Write-gating checker (`cargo xtask check-writes`), the first T6
//! safety-invariant check (SECURITY.md "Enforcement", D-013, story US-RR-7).
//!
//! Rule: every function in `rr-rom` and `rr-comms` that performs a write —
//! overwriting a ROM file, writing ECU memory, resetting an ECU — must take a
//! capability token from `rr_core::capability` as a parameter. Tokens can only
//! be minted on the `rr-app` / `rr-cli` confirmation paths, so a write API
//! that demands one cannot be reached without explicit user confirmation.
//!
//! # Mechanism
//!
//! * **Marker.** Write functions carry `#[rr_write]` from the dependency-free
//!   `rr-write-marker` proc-macro crate (a pass-through attribute: compiler
//!   checked, so a typo is a build error rather than a silently unmarked
//!   function). The crate docs say why a proc-macro beat a naming convention
//!   or a marker trait.
//! * **Enumeration.** This module parses every `.rs` file under the `src/`
//!   of each crate in [`SCAN_CRATES`] with `syn` and lists every function
//!   carrying the marker: free functions, inherent and trait-impl methods,
//!   and trait method declarations, at any visibility.
//! * **Token check.** A marked function passes only if one of its parameters
//!   has a type whose path ends in one of [`TOKEN_TYPES`] (`RomWrite`,
//!   `EcuMemoryWrite`, `EcuReset`), taken by value, `&` or `&mut`. Wrapped
//!   tokens (`Option<RomWrite>`, `Box<RomWrite>`) do not count: an optional
//!   token is a bypass.
//! * **Heuristic net.** So the marker cannot simply be left off, every
//!   *public* function that is not marked is also tested against
//!   [`HEURISTICS`] (one table): a write-ish verb in its name, a `&mut`
//!   parameter whose type looks like a link / image / journal / file, or a
//!   capability-token parameter. A hit is an "unmarked suspected write" and
//!   fails the check. The fix is either `#[rr_write]` plus a token, or
//!   `#[rr_not_write("why this is not a write")]` with a non-empty reason.
//!
//! "Public" here is syntactic and conservative: a `pub` function (in any
//! module, since it might be re-exported), any method in a trait `impl`, and
//! any method declared in a `pub trait`. `&mut self` receivers are not
//! suspect on their own: in-memory edits (e.g. through the patch journal) are
//! not writes; the token gates the save / transmit step. Functions inside a
//! `#[cfg(test)]` module are exempt from the heuristic (they do not ship) but
//! a marked one is still token-checked.
//!
//! Also reported: a function carrying both markers, an `rr_not_write` without
//! a non-empty string-literal justification, and `use ... rr_write as x`
//! renames (which would hide the marker from this scan).
//!
//! # Limits
//!
//! The scan is syntactic. Functions generated by macros (`macro_rules!`
//! bodies, derive output) are not seen; a type alias of a token type
//! (`type T = RomWrite;`) is not resolved and so does not count as a token
//! (fails closed). A source file that does not parse is an error.

use std::collections::BTreeMap;
use std::fmt;
use std::fs;
