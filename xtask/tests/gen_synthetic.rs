//! `cargo xtask gen-synthetic` end to end (US-RR-10-7): the subcommand runs
//! rr-testkit's generator (its `gen-synthetic` example), the output is
//! byte-identical from run to run and to the committed
//! `fixtures/public/synthetic/`, `--check` fails on any tampered committed
//! file, and `.gitattributes` keeps git from rewriting the committed bytes.
//! The generator itself is tested in `crates/rr-testkit/tests/synthetic.rs`;
//! that the output is identical on Windows is shown by the `synthetic` job
//! of `.github/workflows/fixtures.yml` (wiring in `fixtures_ci_config.rs`).

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

use xtask::gen_synthetic::{
    self, COMMITTED_DIR, EXAMPLE, NOT_GENERATED, PACKAGE, SUMS_FILE, read_files,
};

/// The first bytes of `rr_testkit::reference::synthetic::MARKER`.
const MARKER_PREFIX: &[u8] = b"RomRaider-RS SYNTHETIC ROM v1";

/// The ROM-leak guard planned in CONTRIBUTING.md rejects binaries over this
/// size under fixtures/public (US-RR-13).
const LEAK_GUARD_MAX: usize = 64 * 1024;

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn committed() -> PathBuf {
    workspace_root().join(COMMITTED_DIR)
}

fn scratch(name: &str) -> io::Result<PathBuf> {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join("gen-synthetic")
        .join(name);
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

/// Runs `cargo xtask gen-synthetic <args>`; returns the exit code and output.
fn xtask(args: &[&str]) -> io::Result<(i32, String)> {
    let out = Command::new(env!("CARGO_BIN_EXE_xtask"))
        .arg("gen-synthetic")
        .args(args)
        .output()?;
    Ok((
        out.status.code().unwrap_or(-1),
        format!(
            "{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        ),
    ))
}

fn path_arg(p: &Path) -> String {
    p.to_string_lossy().into_owned()
}

/// A copy of the committed directory (including its `.gitattributes`).
fn committed_copy(name: &str) -> io::Result<PathBuf> {
    let dir = scratch(name)?;
    for entry in fs::read_dir(committed())? {
        let entry = entry?;
        fs::copy(entry.path(), dir.join(entry.file_name()))?;
    }
    Ok(dir)
}

#[test]
fn command_runs_the_rr_testkit_generator() {
    let root = workspace_root();
    let cmd = gen_synthetic::command(&root, Path::new("out"));
    let args: Vec<String> = cmd
        .get_args()
        .map(|a| a.to_string_lossy().into_owned())
        .collect();
    let manifest = root.join("Cargo.toml").to_string_lossy().into_owned();
    assert_eq!(
        args,
        [
            "run",
            "--quiet",
            "--manifest-path",
            manifest.as_str(),
            "--package",
            PACKAGE,
            "--example",
            EXAMPLE,
            "--",
            "out"
        ]
    );
}

#[test]
fn generation_is_byte_identical_across_runs_and_to_the_committed_files() -> anyhow::Result<()> {
    let a = scratch("run-a")?;
    let b = scratch("run-b")?;
    for dir in [&a, &b] {
        let (code, out) = xtask(&["--dir", &path_arg(dir)])?;
        assert_eq!(code, 0, "{out}");
    }
    let files_a = read_files(&a)?;
    assert_eq!(files_a, read_files(&b)?, "two runs differ");
    assert!(files_a.contains_key(SUMS_FILE));
    assert!(files_a.keys().any(|n| n.ends_with(".bin")));
    assert!(files_a.keys().any(|n| n.ends_with(".manifest.toml")));
    let problems = gen_synthetic::compare(&files_a, &read_files(&committed())?);
    assert!(
        problems.is_empty(),
        "{COMMITTED_DIR} is out of date (run `cargo xtask gen-synthetic`):\n{}",
        problems.join("\n")
    );

    // A second write into an up-to-date directory changes nothing.
    let (code, out) = xtask(&["--dir", &path_arg(&a)])?;
    assert_eq!(code, 0, "{out}");
    assert!(out.contains("gen-synthetic: unchanged"), "{out}");

    // --check passes on the committed directory (the default) and on a run.
    for args in [vec!["--check"], vec!["--check", "--dir", &path_arg(&a)]] {
        let (code, out) = xtask(&args)?;
        assert_eq!(code, 0, "{args:?}: {out}");
        assert!(out.contains("gen-synthetic: ok"), "{out}");
    }
    Ok(())
}

#[test]
fn check_fails_on_a_tampered_committed_file() -> anyhow::Result<()> {
    type Tamper = fn(&Path) -> io::Result<()>;
    let cases: &[(&str, Tamper, &str)] = &[
        (
            "flipped-rom-byte",
            |d| {
                let p = d.join("standard.bin");
                let mut b = fs::read(&p)?;
                b[0x40] ^= 0x01;
                fs::write(p, b)
            },
            "standard.bin: differs from the generated bytes at offset 0x40",
        ),
        (
            "crlf-manifest",
            |d| {
                let p = d.join("standard.manifest.toml");
                let t = fs::read_to_string(&p)?;
                fs::write(p, t.replace('\n', "\r\n"))
            },
            "\\r\\n line endings",
        ),
        (
            "edited-sums",
            |d| {
                let p = d.join(SUMS_FILE);
                let t = fs::read_to_string(&p)?;
                fs::write(p, t.replacen('a', "b", 1))
            },
            "SHA256SUMS: differs",
        ),
        (
            "missing-manifest",
            |d| fs::remove_file(d.join("standard.manifest.toml")),
            "standard.manifest.toml: missing",
        ),
        (
            "extra-file",
            |d| fs::write(d.join("real-ecu.bin"), [0u8; 16]),
            "real-ecu.bin: not generated",
        ),
    ];
    for (name, tamper, needle) in cases {
        let dir = committed_copy(name)?;
        let (code, out) = xtask(&["--check", "--dir", &path_arg(&dir)])?;
        assert_eq!(code, 0, "{name}: untampered copy fails: {out}");
        tamper(&dir)?;
        let (code, out) = xtask(&["--check", "--dir", &path_arg(&dir)])?;
        assert_eq!(code, 1, "{name}: --check passed a tampered copy: {out}");
        assert!(out.contains(needle), "{name}: expected {needle:?} in {out}");
        // Regenerating repairs it.
        let (code, out) = xtask(&["--dir", &path_arg(&dir)])?;
        assert_eq!(code, 0, "{name}: {out}");
        let (code, out) = xtask(&["--check", "--dir", &path_arg(&dir)])?;
        assert_eq!(code, 0, "{name}: not repaired: {out}");
    }
    Ok(())
}

#[test]
fn committed_roms_are_marked_synthetic_and_small() -> anyhow::Result<()> {
    let files = read_files(&committed())?;
    let roms: Vec<_> = files.iter().filter(|(n, _)| n.ends_with(".bin")).collect();
    assert!(!roms.is_empty(), "no ROM in {COMMITTED_DIR}");
    for (name, bytes) in roms {
        assert!(
            bytes.starts_with(MARKER_PREFIX),
            "{name} has no synthetic marker"
        );
        assert!(
            bytes.len() <= LEAK_GUARD_MAX,
            "{name} is {} bytes",
            bytes.len()
        );
        let manifest = name.replace(".bin", ".manifest.toml");
        let text = String::from_utf8(files[&manifest].clone())?;
        assert!(text.lines().any(|l| l == "synthetic = true"), "{manifest}");
    }
    Ok(())
}

#[test]
fn gitattributes_keep_the_committed_bytes_unconverted() -> anyhow::Result<()> {
    assert!(committed().join(NOT_GENERATED[0]).is_file());
    let files = read_files(&committed())?;
    let paths: Vec<String> = files
        .keys()
        .map(|n| format!("{COMMITTED_DIR}/{n}"))
        .collect();
    let out = Command::new("git")
        .args(["check-attr", "text", "eol", "--"])
        .args(&paths)
        .current_dir(workspace_root())
        .output()?;
    assert!(out.status.success(), "git check-attr failed");
    let attrs = String::from_utf8(out.stdout)?;
    for path in &paths {
        let get = |attr: &str| {
            attrs
                .lines()
                .find_map(|l| l.strip_prefix(&format!("{path}: {attr}: ")))
                .unwrap_or("<none>")
                .to_owned()
        };
        if path.ends_with(".bin") {
            assert_eq!(get("text"), "unset", "{path} must be `binary`");
        } else {
            assert_eq!(
                (get("text").as_str(), get("eol").as_str()),
                ("set", "lf"),
                "{path} must be `text eol=lf`"
            );
        }
    }
    Ok(())
}
